def _print_summary(df: pd.DataFrame, has_loocv: bool) -> None:
    """Print a concise text summary of dataset characteristics."""
    n_runs = len(df)
    n_samples = df["samples"].sum()
    print(f"\nDataset: {n_runs} runs, {n_samples:,.0f} samples")
    print(f"Temperature range: {df['temp'].min():.1f}–{df['temp'].max():.1f}°C\n")

    print("Temperature coverage:")
    for label, lo, hi, _ in BAND_DEFS:
        mask = (df["temp"] >= lo) & (df["temp"] < hi)
        count = mask.sum()
        runs = df[mask]["run"].tolist()
        bar = "█" * count + "░" * (6 - min(count, 6))
        status = "← NEEDS DATA" if count <= 1 else ""
        print(f"  {label}°C  {bar}  {count} runs  ({', '.join(runs)})  {status}")

    print(f"\nStage duration ranges (min):")
    for stage, key in [("Lag", "lag_dur"), ("Exponential", "exp_dur"),
                        ("Peak", "peak_dur"), ("Decline", "dec_dur")]:
        vals = df[key]
        print(f"  {stage:12s}  {vals.min():5.0f} – {vals.max():5.0f}  (mean {vals.mean():.0f})")

    print(f"\nCorrelation (temp vs timing):")
    for col, label in [("exp_start", "Exp start"), ("peak_start", "Peak start"),
                        ("dec_start", "Dec start"), ("duration", "Total duration")]:
        corr = df["temp"].corr(df[col])
        print(f"  temp vs {label:15s}  r = {corr:+.3f}")

    if has_loocv:
        print(f"\nLOOCV error by temperature band:")
        for label, lo, hi, _ in BAND_DEFS:
            mask = (df["temp"] >= lo) & (df["temp"] < hi)
            sub = df[mask]
            if len(sub):
                print(f"  {label}°C  ({len(sub)} runs)  "
                      f"mean MAE={sub['mae'].mean():.1f}  "
                      f"worst MAE={sub['mae'].max():.1f}  "
                      f"max single err={sub['worst'].max():.1f}")


