def _build_run_profiles(raw_df: pd.DataFrame) -> pd.DataFrame:
    """Extract per-run statistics from the raw loaded DataFrame."""
    profiles = []

    for run_id, group in raw_df.groupby("run_id"):
        group = group.sort_values("timestamp").reset_index(drop=True)
        elapsed = (group["timestamp"] - group["timestamp"].iloc[0]).dt.total_seconds() / 60
        dist = group["distance"]
        rise = dist.iloc[0] - dist

        stage_durs = {}
        stage_starts = {}
        for s in range(4):
            mask = group["stage"] == s
            if mask.any():
                start = elapsed[mask].iloc[0]
                end = elapsed[mask].iloc[-1]
                stage_durs[s] = end - start
                stage_starts[s] = start

        # 90% plateau width
        threshold_90 = rise.max() * 0.90
        above_90 = rise >= threshold_90
        if above_90.any():
            plateau_90 = elapsed[above_90].iloc[-1] - elapsed[above_90].iloc[0]
        else:
            plateau_90 = 0.0

        profiles.append({
            "run": str(run_id),
            "temp": group["temperature"].mean(),
            "temp_std": group["temperature"].std(),
            "duration": elapsed.iloc[-1],
            "samples": len(group),
            "total_rise": rise.max(),
            "co2_max": group["co2"].max(),
            "plateau_90": plateau_90,
            "lag_dur": stage_durs.get(0, 0),
            "exp_dur": stage_durs.get(1, 0),
            "peak_dur": stage_durs.get(2, 0),
            "dec_dur": stage_durs.get(3, 0),
            "lag_start": stage_starts.get(0, 0),
            "exp_start": stage_starts.get(1, 0),
            "peak_start": stage_starts.get(2, 0),
            "dec_start": stage_starts.get(3, 0),
        })

    return pd.DataFrame(profiles).sort_values("temp").reset_index(drop=True)


def _merge_loocv(profiles: pd.DataFrame, loocv: dict) -> pd.DataFrame:
    """Merge LOOCV results dict into the profiles DataFrame."""
    loocv_rows = []
    for run_id, data in loocv.items():
        loocv_rows.append({
            "run": str(run_id),
            "mae": data.get("mae", 0),
            "worst": data.get("worst", 0),
            "exp_err": data.get("exp_err", 0),
            "peak_err": data.get("peak_err", 0),
            "dec_err": data.get("dec_err", 0),
        })
    ldf = pd.DataFrame(loocv_rows)
    return profiles.merge(ldf, on="run", how="left")


