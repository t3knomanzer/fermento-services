def analyze(
    data_dir: str,
    loocv_json: str = None,
    output: str = None,
) -> None:
    """
    Analyze the dataset and generate the 7-panel dashboard.

    Args:
        data_dir:   Path to directory of labeled CSV run files.
        loocv_json: Optional path to JSON with per-run LOOCV results.
                    Expected format: {"run_id": {"mae": ..., "worst": ...,
                    "exp_err": ..., "peak_err": ..., "dec_err": ...}, ...}
        output:     Output path for the PNG. Defaults to <data_dir>/analysis.png.
    """
    print(f"Loading runs from: {data_dir}")
    raw_df = load_all_runs(data_dir)
    n_runs = raw_df["run_id"].nunique()
    print(f"  {n_runs} runs, {len(raw_df):,} samples")

    profiles = _build_run_profiles(raw_df)

    # Load LOOCV results if provided
    has_loocv = False
    if loocv_json:
        loocv_path = Path(loocv_json)
        if loocv_path.exists():
            with open(loocv_path) as f:
                loocv = json.load(f)
            profiles = _merge_loocv(profiles, loocv)
            has_loocv = True
            print(f"  LOOCV results loaded from {loocv_json}")
        else:
            print(f"  Warning: LOOCV file not found: {loocv_json}")

    # Fill missing LOOCV columns with zeros for plotting
    for col in ["mae", "worst", "exp_err", "peak_err", "dec_err"]:
        if col not in profiles.columns:
            profiles[col] = 0.0

    _print_summary(profiles, has_loocv)

    # --- Generate dashboard ---
    _apply_style()

    if has_loocv:
        fig = plt.figure(figsize=(20, 24))
        gs = gridspec.GridSpec(4, 2, figure=fig,
            hspace=0.35, wspace=0.25,
            left=0.07, right=0.95, top=0.95, bottom=0.04)
    else:
        # Without LOOCV: skip error panels (2, 4, 5), show 4 panels
        fig = plt.figure(figsize=(20, 14))
        gs = gridspec.GridSpec(2, 2, figure=fig,
            hspace=0.35, wspace=0.25,
            left=0.07, right=0.95, top=0.93, bottom=0.06)

    fig.patch.set_facecolor(BG)
    fig.suptitle("Fermento — Dataset Analysis & Model Gaps",
                 fontsize=20, fontweight="bold", color=WHITE, y=0.975)

    if has_loocv:
        _plot_temp_histogram(fig.add_subplot(gs[0, 0]), profiles)
        _plot_mae_vs_temp(fig.add_subplot(gs[0, 1]), profiles)
        _plot_stage_durations(fig.add_subplot(gs[1, :]), profiles)
        _plot_per_stage_errors(fig.add_subplot(gs[2, 0]), profiles)
        _plot_coverage_vs_mae(fig.add_subplot(gs[2, 1]), profiles)
        _plot_temp_vs_duration(fig.add_subplot(gs[3, 0]), profiles)
        _plot_co2_vs_temp(fig.add_subplot(gs[3, 1]), profiles, has_loocv)
    else:
        _plot_temp_histogram(fig.add_subplot(gs[0, 0]), profiles)
        _plot_stage_durations(fig.add_subplot(gs[0, 1]), profiles)
        _plot_temp_vs_duration(fig.add_subplot(gs[1, 0]), profiles)
        _plot_co2_vs_temp(fig.add_subplot(gs[1, 1]), profiles, has_loocv)

    out_path = Path(output) if output else Path(data_dir) / "analysis.png"
    plt.savefig(out_path, dpi=150, bbox_inches="tight", facecolor=BG)
    plt.close()
    print(f"\n✓ Dashboard saved → {out_path}")
