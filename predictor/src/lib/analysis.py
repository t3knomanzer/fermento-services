def _plot_temp_histogram(ax, df):
    """Panel 1: Temperature distribution with gap highlighting."""
    bins = np.arange(22, 36.5, 1)
    n, bin_edges, patches = ax.hist(df["temp"], bins=bins, edgecolor=PANEL, linewidth=1.2, alpha=0.9)
    for patch, left_edge in zip(patches, bin_edges[:-1]):
        if left_edge < 25:   patch.set_facecolor("#60a5fa")
        elif left_edge < 28: patch.set_facecolor("#34d399")
        elif left_edge < 31: patch.set_facecolor("#fbbf24")
        elif left_edge < 34: patch.set_facecolor("#fb923c")
        else:                patch.set_facecolor("#f87171")

    # Highlight thin bands
    for label, lo, hi, _ in BAND_DEFS:
        count = ((df["temp"] >= lo) & (df["temp"] < hi)).sum()
        if count <= 1:
            ax.axvspan(lo, hi, alpha=0.08, color=RED, zorder=0)
            ax.annotate(
                f"THIN COVERAGE\n{count} run{'s' if count != 1 else ''} only",
                xy=((lo + hi) / 2, max(n) * 0.75), fontsize=8,
                color=RED, ha="center", fontweight="bold",
                bbox=dict(boxstyle="round,pad=0.3", fc=BG, ec=RED, alpha=0.8),
            )

    ax.set_xlabel("Mean Temperature (°C)")
    ax.set_ylabel("Number of Runs")
    ax.set_title("Temperature Distribution", fontsize=12, fontweight="bold", color=WHITE, pad=10)
    ax.grid(axis="y", alpha=0.3)
    ax.set_xlim(21.5, 36)


def _plot_mae_vs_temp(ax, df):
    """Panel 2: MAE vs temperature scatter."""
    colors = [RED if m > 30 else AMBER if m > 15 else GREEN for m in df["mae"]]
    sizes = [max(40, min(300, m * 3)) for m in df["mae"]]

    ax.scatter(df["temp"], df["mae"], c=colors, s=sizes, alpha=0.85,
               edgecolors=PANEL, linewidth=1, zorder=3)

    for _, r in df.iterrows():
        if r["mae"] > 20:
            ax.annotate(f'Run {r["run"]}', (r["temp"], r["mae"]),
                        textcoords="offset points", xytext=(8, 5),
                        fontsize=7.5, color=RED, fontweight="bold")
        elif r["mae"] < 6:
            ax.annotate(f'Run {r["run"]}', (r["temp"], r["mae"]),
                        textcoords="offset points", xytext=(8, -2),
                        fontsize=7, color=GREEN, alpha=0.8)

    ax.axhline(15, color=AMBER, linewidth=0.8, linestyle="--", alpha=0.5)
    ax.text(ax.get_xlim()[1] - 0.2, 15.5, "15 min", fontsize=7, color=AMBER, ha="right")
    ax.axhline(30, color=RED, linewidth=0.8, linestyle="--", alpha=0.5)
    ax.text(ax.get_xlim()[1] - 0.2, 31, "30 min", fontsize=7, color=RED, ha="right")

    ax.set_xlabel("Mean Temperature (°C)")
    ax.set_ylabel("MAE (min)")
    ax.set_title("LOOCV Error vs Temperature", fontsize=12, fontweight="bold", color=WHITE, pad=10)
    ax.grid(alpha=0.3)


def _plot_stage_durations(ax, df):
    """Panel 3: Stacked stage duration bars sorted by temperature."""
    bar_width = 0.7
    x = np.arange(len(df))
    bottoms = np.zeros(len(df))

    for stage, key in [("Lag", "lag_dur"), ("Exponential", "exp_dur"),
                        ("Peak", "peak_dur"), ("Decline", "dec_dur")]:
        vals = df[key].values
        ax.bar(x, vals, bar_width, bottom=bottoms, label=stage,
               color=STAGE_C[stage], edgecolor=PANEL, linewidth=0.5, alpha=0.88)
        bottoms += vals

    for i, r in df.iterrows():
        ax.text(i, r["duration"] + 12, f'{r["temp"]:.1f}°', ha="center", fontsize=7, color=DIMTXT)

    ax.set_xticks(x)
    ax.set_xticklabels([f'Run {r}' for r in df["run"]], rotation=45, ha="right", fontsize=8)
    ax.set_ylabel("Duration (min)")
    ax.set_title("Stage Durations by Run (sorted by temperature, coldest → hottest)",
                 fontsize=12, fontweight="bold", color=WHITE, pad=10)
    ax.legend(loc="upper right", fontsize=8, framealpha=0.3, edgecolor=GRID,
              facecolor=BG, labelcolor=BRIGHT)
    ax.grid(axis="y", alpha=0.3)


def _plot_per_stage_errors(ax, df):
    """Panel 4: Per-stage absolute transition errors."""
    bar_w = 0.25
    x = np.arange(len(df))

    for i, (key, label, color) in enumerate([
        ("exp_err", "Exponential", STAGE_C["Exponential"]),
        ("peak_err", "Peak", STAGE_C["Peak"]),
        ("dec_err", "Decline", STAGE_C["Decline"]),
    ]):
        vals = df[key].abs().values
        ax.bar(x + i * bar_w, vals, bar_w, label=label, color=color,
               alpha=0.8, edgecolor=PANEL, linewidth=0.5)

    ax.set_xticks(x + bar_w)
    ax.set_xticklabels([f'{r}' for r in df["run"]], rotation=45, ha="right", fontsize=7.5)
    ax.set_ylabel("|Error| (min)")
    ax.set_xlabel("Run")
    ax.set_title("Transition Error by Stage", fontsize=12, fontweight="bold", color=WHITE, pad=10)
    ax.legend(fontsize=8, framealpha=0.3, edgecolor=GRID, facecolor=BG, labelcolor=BRIGHT)
    ax.grid(axis="y", alpha=0.3)

    # Cap y-axis for readability, annotate clipped bars
    y_cap = 100
    ax.set_ylim(0, y_cap)
    for _, r in df.iterrows():
        for key in ["exp_err", "peak_err", "dec_err"]:
            if abs(r[key]) > y_cap * 0.95:
                idx = df.index.get_loc(r.name)
                offset = {"exp_err": 0, "peak_err": 1, "dec_err": 2}[key]
                ax.annotate(f"{abs(r[key]):.0f}", (idx + offset * bar_w, y_cap * 0.97),
                            fontsize=7, color=RED, ha="center", fontweight="bold")


def _plot_coverage_vs_mae(ax, df):
    """Panel 5: Run count and avg MAE per temperature band."""
    band_stats = []
    for label, lo, hi, color in BAND_DEFS:
        mask = (df["temp"] >= lo) & (df["temp"] < hi)
        sub = df[mask]
        band_stats.append({
            "label": label,
            "count": len(sub),
            "avg_mae": sub["mae"].mean() if len(sub) else 0,
            "color": color,
        })

    bdf = pd.DataFrame(band_stats)
    x = np.arange(len(bdf))

    ax.bar(x - 0.2, bdf["count"], 0.35,
           color=[b["color"] for b in band_stats],
           alpha=0.85, edgecolor=PANEL, linewidth=0.8, label="# Runs")

    ax2 = ax.twinx()
    ax2.bar(x + 0.2, bdf["avg_mae"], 0.35,
            color=[b["color"] for b in band_stats],
            alpha=0.4, edgecolor=[b["color"] for b in band_stats],
            linewidth=1.5, linestyle="--", label="Avg MAE")

    ax.set_xticks(x)
    ax.set_xticklabels(bdf["label"], fontsize=9)
    ax.set_ylabel("Number of Runs", color=BRIGHT)
    ax2.set_ylabel("Avg MAE (min)", color=DIMTXT)
    ax2.tick_params(colors=DIMTXT)
    ax.set_title("Coverage vs Error by Temperature Band",
                 fontsize=12, fontweight="bold", color=WHITE, pad=10)
    ax.grid(axis="y", alpha=0.2)

    lines1, labels1 = ax.get_legend_handles_labels()
    lines2, labels2 = ax2.get_legend_handles_labels()
    ax.legend(lines1 + lines2, labels1 + labels2, fontsize=8, framealpha=0.3,
              edgecolor=GRID, facecolor=BG, labelcolor=BRIGHT, loc="upper right")


def _plot_temp_vs_duration(ax, df):
    """Panel 6: Temperature vs duration scatter with trend lines."""
    ax.scatter(df["temp"], df["duration"], s=60, color=CYAN, alpha=0.8,
               label="Total duration", zorder=3, edgecolors=PANEL)
    ax.scatter(df["temp"], df["exp_dur"], s=40, color=STAGE_C["Exponential"],
               alpha=0.8, label="Exp duration", zorder=3, edgecolors=PANEL)
    ax.scatter(df["temp"], df["peak_dur"], s=40, color=STAGE_C["Peak"],
               alpha=0.8, label="Peak duration", zorder=3, edgecolors=PANEL)

    t_smooth = np.linspace(df["temp"].min(), df["temp"].max(), 100)
    for vals, c in [(df["duration"], CYAN),
                    (df["exp_dur"], STAGE_C["Exponential"]),
                    (df["peak_dur"], STAGE_C["Peak"])]:
        z = np.polyfit(df["temp"], vals, 2)
        ax.plot(t_smooth, np.poly1d(z)(t_smooth), color=c, alpha=0.3,
                linewidth=1.5, linestyle="--")

    # Annotate the coldest run if it's a clear outlier
    coldest = df.iloc[0]
    if coldest["duration"] > df["duration"].median() * 1.5:
        ax.annotate(
            f'Run {coldest["run"]}\n{coldest["duration"]:.0f} min total\n'
            f'{coldest["exp_dur"]:.0f} min Exp\n{coldest["peak_dur"]:.0f} min Peak',
            (coldest["temp"], coldest["duration"]),
            textcoords="offset points", xytext=(15, -10),
            fontsize=7, color=RED, fontweight="bold",
            arrowprops=dict(arrowstyle="->", color=RED, lw=0.8),
            bbox=dict(boxstyle="round,pad=0.3", fc=BG, ec=RED, alpha=0.8),
        )

    ax.set_xlabel("Mean Temperature (°C)")
    ax.set_ylabel("Duration (min)")
    ax.set_title("Temperature vs Duration (non-linear relationship)",
                 fontsize=12, fontweight="bold", color=WHITE, pad=10)
    ax.legend(fontsize=8, framealpha=0.3, edgecolor=GRID, facecolor=BG, labelcolor=BRIGHT)
    ax.grid(alpha=0.3)


def _plot_co2_vs_temp(ax, df, has_loocv: bool):
    """Panel 7: Max CO₂ vs temperature, colored by MAE if available."""
    from matplotlib.lines import Line2D

    if has_loocv:
        colors = [RED if r["mae"] > 30 else AMBER if r["mae"] > 15 else GREEN
                  for _, r in df.iterrows()]
    else:
        colors = [CYAN] * len(df)

    ax.scatter(df["temp"], df["co2_max"] / 1000, s=70, c=colors, alpha=0.85,
               edgecolors=PANEL, linewidth=1, zorder=3)

    for _, r in df.iterrows():
        if r["co2_max"] < 20000 or r["co2_max"] > 43000:
            ax.annotate(f'Run {r["run"]}', (r["temp"], r["co2_max"] / 1000),
                        textcoords="offset points", xytext=(8, 3),
                        fontsize=7, color=DIMTXT)

    ax.axhspan(0, 20, alpha=0.05, color=RED, zorder=0)
    ax.text(ax.get_xlim()[1] - 0.3, 18.5, "Low CO₂ zone\n(under-represented)",
            fontsize=7.5, color=RED, ha="right", alpha=0.7)

    ax.set_xlabel("Mean Temperature (°C)")
    ax.set_ylabel("Max CO₂ (×1000 ppm)")

    if has_loocv:
        ax.set_title("Max CO₂ vs Temperature (color = MAE severity)",
                     fontsize=12, fontweight="bold", color=WHITE, pad=10)
        legend_elements = [
            Line2D([0], [0], marker='o', color='none', markerfacecolor=GREEN, markersize=8, label='MAE ≤ 15'),
            Line2D([0], [0], marker='o', color='none', markerfacecolor=AMBER, markersize=8, label='15 < MAE ≤ 30'),
            Line2D([0], [0], marker='o', color='none', markerfacecolor=RED, markersize=8, label='MAE > 30'),
        ]
        ax.legend(handles=legend_elements, fontsize=8, framealpha=0.3,
                  edgecolor=GRID, facecolor=BG, labelcolor=BRIGHT)
    else:
        ax.set_title("Max CO₂ vs Temperature",
                     fontsize=12, fontweight="bold", color=WHITE, pad=10)

    ax.grid(alpha=0.3)


